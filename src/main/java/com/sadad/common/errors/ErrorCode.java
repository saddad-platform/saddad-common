/**
 * Every error this platform can report, with the wording it falls back to.
 *
 * <p><b>Why the codes live in code and the wording lives in data.</b> This mirrors the
 * split the platform already uses for permissions, and for the same reasons. The SET of
 * codes is a contract between services, the admin console and both portals: it must be
 * checkable at compile time, because a mistyped code is not a compile error anywhere else -
 * it silently produces an untranslated message that only the customer ever sees. The WORDING
 * is editorial. It gets revised by people who are not deploying software, it differs per
 * language, and it must be changeable on a Tuesday afternoon without a release. So the codes
 * are here and the text is in {@code error_catalog_entries}, editable in the admin console,
 * with these values as the seed and the permanent fallback.
 *
 * <p><b>Every code carries both languages.</b> Not because the database is unreliable, but
 * because the failure path must not have a dependency. A service that cannot reach
 * saddad-admin - during a cold start, a deploy, or an outage - still has to tell a customer
 * what went wrong, in their language. A catalogue that only lived in the database would be
 * unreachable at precisely the moment it is most needed.
 *
 * <p><b>On the Arabic.</b> These are written as a Saudi corporate user would expect to read
 * them, not as transliterated English. Numbers, reference numbers and IBANs stay in Latin
 * digits in both languages, matching the rest of the platform, because those are values a
 * user reads back to a support agent.
 *
 * <p><b>Placeholders</b> are {@code {named}} and are listed in {@link #params} so a guard
 * test can check that both translations use exactly the declared set - a placeholder present
 * in English and missing in Arabic is a fact silently dropped for Arabic readers.
 */
