    private final int httpStatus;
    private final String category;
    private final String severity;
    /**
     * Whether this sentence may be shown to a customer as it is.
     *
     * <p>Separate from {@link #severity}, which says how loudly operators should hear about
     * it. "Your session has ended" is CRITICAL to monitor and entirely safe to display;
     * "The Wathq provider is not configured" is a sentence about our own deployment and
     * tells a customer nothing they can act on. When this is false the resolver substitutes
     * the generic failure message, and the specific one goes only to the logs.
     */
    private final boolean userSafe;
    private final String defaultMessageEn;
    private final String defaultMessageAr;
    /** The placeholder names both translations are expected to use. */
    private final java.util.List<String> params;

    ErrorCode(int httpStatus, String category, String severity,
              String defaultMessageEn, String defaultMessageAr, String... params) {
        this(httpStatus, category, severity, true, defaultMessageEn, defaultMessageAr, params);
    }

    ErrorCode(int httpStatus, String category, String severity, boolean userSafe,
              String defaultMessageEn, String defaultMessageAr, String... params) {
        this.httpStatus = httpStatus;
        this.category = category;
        this.severity = severity;
        this.userSafe = userSafe;
        this.defaultMessageEn = defaultMessageEn;
        this.defaultMessageAr = defaultMessageAr;
        this.params = java.util.List.of(params);
    }

    /** The wire code. Same as {@link #name()} - stated explicitly because it is a contract
     * with both portals and with every other service, not an implementation detail. */
    public String code() {
        return name();
    }

    private static final Map<String, ErrorCode> BY_CODE = Arrays.stream(values())
            .collect(Collectors.toUnmodifiableMap(ErrorCode::code, Function.identity()));

    /** Empty for a code this build does not know - an older service, or a row an operator
     * added by hand. Callers fall back to the message the exception carried. */
    public static Optional<ErrorCode> find(String code) {
        return code == null ? Optional.empty() : Optional.ofNullable(BY_CODE.get(code));
    }
